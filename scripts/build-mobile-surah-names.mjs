const surahs = JSON.parse(fs.readFileSync(path.join(root, "data/quran/surahs.json"), "utf8"));
if (surahs.length !== 114 || TRANSLIT.length !== 114) throw new Error("114 sure bekleniyor");
const out = surahs.map((s, i) => {
  if (s.number !== i + 1) throw new Error(`sıra bozuk: ${s.number}`);
  return { name: TRANSLIT[i], meaning: s.englishName };
});
fs.writeFileSync(path.join(root, "apps/mobile/src/data/surahNamesEn.json"), JSON.stringify(out) + "\n");
