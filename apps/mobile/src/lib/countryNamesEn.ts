/** Diyanet'in Türkçe ülke adının İngilizcesi; tabloda yoksa null (çağıran Türkçe adı gösterir). */
export function countryNameEn(diyanetCountry: string): string | null {
  return COUNTRY_NAMES_EN[diyanetCountry.trim().toLocaleUpperCase("tr")] ?? null;
}

/** Diyanet'in Türkçe eyalet adlarından İngilizcesi farklı olanlar (diğerleri zaten yerel/İngilizce). */
const STATE_NAMES_EN: Readonly<Record<string, string>> = {
  "HAVAI ADALARI": "Hawaii",
};

type CityParts = { name: string; state: string; country: string };

/**
 * Şehir listesindeki alt satır: "Eyalet, Ülke" ya da yalnız "Ülke".
 * - Eyalet adı şehir adıyla ya da ülke adıyla aynıysa tekrar yazılmaz ("Fransa, Fransa" olmaz).
 * - lang "en" iken ülke (ve bilinen eyalet) adları İngilizceye çevrilir; Türkiye'de değişmez.
 * `titleCase` dışarıdan verilir (diyanetPrayer.titleCaseTr) — modül saf kalsın diye.
 */
export function citySubtitle(
  city: CityParts,
  lang: "tr" | "en",
  isTurkey: boolean,
  titleCase: (upper: string, turkish?: boolean) => string,
): string {
  const key = (s: string) => s.trim().toLocaleUpperCase("tr");
  const sameAsCountry = key(city.state) === key(city.country);
  const sameAsName = key(city.state) === key(city.name);
  const en = lang === "en" && !isTurkey;
  const country = (en && countryNameEn(city.country))
    || (key(city.country) === "ABD" ? "ABD" : titleCase(city.country, isTurkey));
  const state = sameAsCountry || sameAsName
    ? ""
    : (en && STATE_NAMES_EN[key(city.state)]) || titleCase(city.state, isTurkey);
  return [state, country].filter((part) => part.length > 0).join(", ");
}

