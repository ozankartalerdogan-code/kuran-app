const { withAppBuildGradle } = require('expo/config-plugins');

const marker = '// @generated by with-native-clean-codegen-ordering';

const orderingBlock = [
  marker,
  'gradle.projectsEvaluated {',
  "    def appProject = project(':app')",
  '    def appExternalNativeCleanTasks = appProject.tasks.matching { task ->',
  "        task.name.startsWith('externalNativeBuildClean')",
  '    }',
  '',
  '    rootProject.subprojects.each { subproject ->',
  '        if (subproject != appProject) {',
  '            subproject.tasks.configureEach { task ->',
  '                if (',
  "                    task.name == 'clean' ||",
  "                    task.name.startsWith('externalNativeBuildClean') ||",
  "                    task.name == 'cleanCmakeCache'",
  '                ) {',
  '                    appExternalNativeCleanTasks.configureEach { appNativeClean ->',
  '                        task.mustRunAfter(appNativeClean)',
  '                    }',
  '                }',
  '            }',
  '        }',
  '    }',
  '}',
].join('\n');

/**
 * Keep React Native Codegen JNI sources available until app-level CMake clean
 * finishes. App CMake reconfiguration consumes autolinked module JNI sources.
 */
module.exports = function withNativeCleanCodegenOrdering(config) {
  return withAppBuildGradle(config, (config) => {
    const markerIndex = config.modResults.contents.indexOf(marker);
    config.modResults.contents =
      markerIndex >= 0
        ? config.modResults.contents.slice(0, markerIndex).trimEnd() + '\n\n' + orderingBlock + '\n'
        : config.modResults.contents + '\n\n' + orderingBlock + '\n';
    return config;
  });
};